const PLAN_SECTION_TITLES = [
  ["executive_summary", "01. Executive Summary"],
  ["business_introduction", "02. Business Introduction"],
  ["problem_statement", "03. Problem Statement"],
  ["proposed_solution", "04. Proposed Solution"],
  ["target_market", "05. Target Market"],
  ["competitor_analysis", "06. Competitor Analysis"],
  ["marketing_strategy", "07. Marketing Strategy"],
  ["investment_requirements", "08. Investment Requirements"],
  ["revenue_model", "09. Revenue Model"],
  ["risk_analysis", "10. Risk Analysis"],
  ["future_growth", "11. Future Growth"],
];

export function downloadBusinessPlanPdf(plan) {
  const jsPDF = window.jspdf?.jsPDF;
  if (!jsPDF) {
    throw new Error("PDF library is not loaded yet. Please refresh and try again.");
  }

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;
  let y = 56;

  // Header Banner
  doc.setFillColor(11, 19, 43);
  doc.rect(0, 0, pageWidth, 88, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text(String(plan.business_name || "Startup Business Plan"), margin, 42);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  doc.text(
    `Industry: ${plan.industry || "General"}  |  Generated by EntrepreneurAI`,
    margin,
    64
  );

  y = 114;
  doc.setTextColor(146, 64, 14);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(9.5);
  const notice = doc.splitTextToSize(
    "Note: Market observations and financial figures contained in this business plan are AI-assisted planning estimates and should be validated against local primary data before capital commitment.",
    maxWidth
  );
  doc.text(notice, margin, y);
  y += notice.length * 13 + 14;

  const sections = plan.sections || {};
  for (const [key, title] of PLAN_SECTION_TITLES) {
    const body = String(sections[key] || "").trim();
    if (!body) continue;

    if (y > pageHeight - 100) {
      doc.addPage();
      y = 54;
    }

    doc.setTextColor(37, 99, 235);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12.5);
    doc.text(title, margin, y);
    y += 18;

    doc.setTextColor(15, 23, 42);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10.5);

    const lines = doc.splitTextToSize(body, maxWidth);
    for (const line of lines) {
      if (y > pageHeight - 54) {
        doc.addPage();
        y = 54;
      }
      doc.text(line, margin, y);
      y += 14.5;
    }
    y += 14;
  }

  const slug = String(plan.business_name || "business-plan")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  doc.save(`${slug || "business-plan"}.pdf`);
}
